//! The frontend's wire types, rendered from the Rust types with ts-rs.
//!
//! `wire_types_ts()` is the text of `apps/desktop/src/client/generated.ts`;
//! `tests/wire_types.rs` keeps the file current.

use ts_rs::{Config, TS};

use crate::action::ACTIONS;
use crate::view::PlacementView;
use crate::{
    AcidStepView, Action, Change, DrumHitDto, ErrorView, Event, ExternalChange, FxView, LaneView,
    MixView, NoteView, ParamView, PatternView, RunTag, SectionView, SongView, Source,
    StudioCommand, StudioState, TrackView,
};

/// `Command` is `StudioCommand | Action` on the wire (its `Deserialize`
/// routes by `cmd` name), which a derive cannot say, so it is written here.
const COMMAND_DECL: &str = "type Command = StudioCommand | Action;";

/// The studio's wire types as TypeScript source, one `export` per type.
pub fn wire_types_ts() -> String {
    let cfg = Config::new();
    let mut out = String::from(
        "// Generated by `UPDATE_GOLDEN=1 cargo test -p tune-studio --test wire_types` from crates/tune-studio. Do not edit.\n\n",
    );
    let mut decl = |d: String| {
        out.push_str("export ");
        out.push_str(&d);
        out.push('\n');
    };
    decl(serde_json::Value::decl(&cfg));
    decl(Source::decl(&cfg));
    decl(DrumHitDto::decl(&cfg));
    decl(ErrorView::decl(&cfg));
    decl(Change::decl(&cfg));
    decl(RunTag::decl(&cfg));
    decl(ExternalChange::decl(&cfg));
    decl(ParamView::decl(&cfg));
    decl(FxView::decl(&cfg));
    decl(PlacementView::decl(&cfg));
    decl(TrackView::decl(&cfg));
    decl(MixView::decl(&cfg));
    decl(AcidStepView::decl(&cfg));
    decl(NoteView::decl(&cfg));
    decl(PatternView::decl(&cfg));
    decl(LaneView::decl(&cfg));
    decl(SectionView::decl(&cfg));
    decl(SongView::decl(&cfg));
    decl(StudioState::decl(&cfg));
    decl(Event::decl(&cfg));
    decl(Action::decl(&cfg));
    decl(StudioCommand::decl(&cfg));
    decl(COMMAND_DECL.to_owned());
    let names = |it: Vec<&str>| {
        it.iter()
            .map(|n| format!("\"{n}\""))
            .collect::<Vec<_>>()
            .join(", ")
    };
    out.push_str(&format!(
        "export const ACTION_NAMES = [{}] as const;\n",
        names(ACTIONS.iter().map(|a| a.name).collect())
    ));
    out.push_str(&format!(
        "export const STUDIO_COMMAND_NAMES = [{}] as const;\n",
        names(vec![
            "list_songs",
            "get_state",
            "open_song",
            "resolve_offered"
        ])
    ));
    out
}
